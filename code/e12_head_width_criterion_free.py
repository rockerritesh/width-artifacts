#!/usr/bin/env python3
"""E12 (camera-ready, reviewer vd7n): criterion-free head widths.

The Fig-2 sweep ablates only heads passing the previous-token role criterion,
so "n_w matches k*_eff" is partly circular. Two criterion-free selections, run in
gpt2-mech-interp (same eval, seed, batches, reader as m5w):
  m5x: rank every upstream head by its OWN single-head ablation drop (a width-1
       ranking, so it can miss heads that matter only jointly), sweep top-K.
  m5y: greedy forward selection by JOINT ablation drop. No role score enters.
Plus IOI: R3 greedy backward elimination over all 144 GPT-2 heads.

Writes results/e12_head_width.json and paper/table_heads.tex.
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path("/path/to/Documents/workspace")
P = ROOT / "interp4discovery-neurips2026"
G = ROOT / "gpt2-mech-interp/results"
MODELS = [("gpt2", "GPT-2 small"), ("gpt2-medium", "GPT-2 medium"),
          ("gpt2-large", "GPT-2 large"), ("gpt2-xl", "GPT-2 XL"),
          ("EleutherAI_pythia-410m", "Pythia-410m"),
          ("EleutherAI_pythia-1.4b", "Pythia-1.4b"),
          ("meta-llama_Llama-3.2-1B", "Llama-3.2-1B")]

rows, out = [], {}
for key, lab in MODELS:
    w = np.load(G / f"m5w_{key}.npz", allow_pickle=True)
    crit_drop = float(w["base_score"][0] - w["width_treat"][-1])
    n_w = len(w["width_treat"])
    r = dict(n_w=n_w, criterion_drop=crit_drop)
    fx = G / f"m5x_{key}.npz"
    if fx.exists():
        x = np.load(fx, allow_pickle=True)
        r["single_rank_k_eff"] = int(x["k_eff"][0])
    fy = G / f"m5y_{key}.npz"
    if fy.exists():
        y = np.load(fy, allow_pickle=True)
        d = y["width_drop"]
        r.update(joint_k_eff=int(y["k_eff"][0]), joint_max=float(d.max()),
                 joint_w1=float(d[0] / d.max()), overlap=int(y["overlap"][0]),
                 crit_frac_of_joint=crit_drop / float(d.max()),
                 joint_last5_rel=float(d[-5:].min() / d.max()))
    out[key] = r
    rows.append((lab, r))
    print(lab, r)

r3 = np.load(G / "r3_greedy_discovery.npz", allow_pickle=True)
tr = r3["trace"]
kept = np.arange(144, -1, -1)
frac = (tr - tr[-1]) / (tr[0] - tr[-1])
ioi = {str(t): int(kept[frac >= t].min()) for t in (0.5, 0.9, 0.95)}
out["ioi_r3"] = ioi
(P / "results/e12_head_width.json").write_text(json.dumps(out, indent=1))


def g(r, k, fmt="{}"):
    return fmt.format(r[k]) if k in r else "---"


L = [r"% AUTO-GENERATED by code/e12_head_width_criterion_free.py -- do not edit by hand",
     r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule",
     r"model & $n_w$ (criterion) & $k^*_{\mathrm{eff}}$ single-rank & "
     r"$k^*_{\mathrm{eff}}$ joint & overlap & width 1 & criterion set \\",
     r"\midrule"]
for lab, r in rows:
    L.append(f"{lab} & {r['n_w']} & {g(r, 'single_rank_k_eff')} & "
             f"{g(r, 'joint_k_eff')} & "
             f"{(str(r['overlap']) + '/' + str(r['n_w'])) if 'overlap' in r else '---'} & "
             f"{g(r, 'joint_w1', '{:.2f}')} & {g(r, 'crit_frac_of_joint', '{:.2f}')} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
(P / "paper/table_heads.tex").write_text("\n".join(L) + "\n")
print("IOI R3:", ioi)
print("wrote paper/table_heads.tex")

# ---------------- macros: paper/stats_heads.tex ----------------
from scipy.stats import spearmanr

J = [r for _, r in rows]
cliff, w1j = [], []
for key, _ in MODELS:
    w = np.load(G / f"m5w_{key}.npz", allow_pickle=True)
    lad = np.sort(np.nan_to_num(w["prev_token_scores"]).ravel())[::-1]
    cliff.append(float(lad[0] / lad[1]))
    w1j.append(out[key]["joint_w1"])
rho, pv = spearmanr(cliff, w1j)
gpt = [out[k] for k in ("gpt2", "gpt2-medium", "gpt2-large", "gpt2-xl")]
Mh = {
    "HeadJointKeffMin": min(r["joint_k_eff"] for r in J),
    "HeadJointKeffMax": max(r["joint_k_eff"] for r in J),
    "HeadCritFracMin": f"{min(r['crit_frac_of_joint'] for r in J):.2f}",
    "HeadCritFracMax": f"{max(r['crit_frac_of_joint'] for r in J):.2f}",
    "HeadGptCritFracMin": f"{min(r['crit_frac_of_joint'] for r in gpt):.2f}",
    "HeadGptCritFracMax": f"{max(r['crit_frac_of_joint'] for r in gpt):.2f}",
    "HeadGptKeffMin": min(r["joint_k_eff"] for r in gpt),
    "HeadGptKeffMax": max(r["joint_k_eff"] for r in gpt),
    "HeadXlOverlap": f"{out['gpt2-xl']['overlap']}/{out['gpt2-xl']['n_w']}",
    "HeadPythiaSmallKeff": out["EleutherAI_pythia-410m"]["joint_k_eff"],
    "HeadPythiaSmallNw": out["EleutherAI_pythia-410m"]["n_w"],
    "HeadCliffJointRho": f"{rho:.2f}",
    "HeadCliffJointP": f"{pv:.3f}",
    "IoiFreeNinety": ioi["0.9"],
    "IoiFreeNinetyFive": ioi["0.95"],
}
out["cliff_vs_joint_w1"] = dict(rho=float(rho), p=float(pv), n=len(cliff))
(P / "results/e12_head_width.json").write_text(json.dumps(out, indent=1))
(P / "paper/stats_heads.tex").write_text(
    "% AUTO-GENERATED by code/e12_head_width_criterion_free.py -- do not edit by hand\n"
    + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in Mh.items()))
print("wrote paper/stats_heads.tex", Mh)
